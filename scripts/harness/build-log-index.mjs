import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { root } from './lib.mjs';

function entriesFrom(source, file) {
  const matches = [...source.matchAll(/^#{2,3} (20\d{2}-\d{2}[^\n]*)$/gm)];
  return matches.map((match, index) => {
    const end = matches[index + 1]?.index ?? source.length;
    const block = source.slice(match.index, end).trim();
    const firstDetail = block.split('\n').find((line) => /^[-*] /.test(line)) ?? '';
    return { heading: match[1], detail: firstDetail.replace(/^[-*] /, ''), file };
  });
}

const logsDirectory = path.join(root, 'logs');
const monthlyFiles = readdirSync(logsDirectory)
  .filter((name) => /^20\d{2}-\d{2}\.md$/.test(name))
  .sort();
const entries = monthlyFiles.flatMap((file) => entriesFrom(
  readFileSync(path.join(logsDirectory, file), 'utf8'),
  file,
));
const recent = entries.slice(-20).reverse();
const output = `# Recent Change Index

This file is generated by \`npm run log:index\`. Edit the current monthly log, not this file.

## Recent entries

${recent.map((entry) => `- [${entry.heading}](${entry.file})${entry.detail ? ` — ${entry.detail}` : ''}`).join('\n')}

## Monthly archives

${monthlyFiles.slice().reverse().map((file) => `- [${file.replace('.md', '')}](${file})`).join('\n')}
`;
const outputPath = path.join(logsDirectory, 'index.md');

if (process.argv.includes('--check')) {
  const actual = readFileSync(outputPath, 'utf8');
  if (actual !== output) {
    console.error('logs/index.md is stale. Run npm run log:index and commit the result.');
    process.exit(1);
  }
  console.log(`✓ logs/index.md matches ${entries.length} archived change entries`);
} else {
  writeFileSync(outputPath, output, 'utf8');
  console.log(`✓ logs/index.md rebuilt from ${entries.length} archived change entries`);
}
