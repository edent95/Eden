"""Regenerate seo-text-width.ts: the East Asian Width table behind textWidth().

The yardstick is personal-dashboard's scripts/py/seo_rules.py `text_width()`
(the site-health crawl that grades eden-tan.com): a character whose
unicodedata.east_asian_width is W (wide) or F (fullwidth) counts 2, everything else 1.
JavaScript has no East_Asian_Width property, so the W/F code point ranges are baked in.

    python3 scripts/seo/gen-text-width.py > seo-text-width.ts
"""
import unicodedata

DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'


def b36(n: int) -> str:
    out = ''
    while True:
        out = DIGITS[n % 36] + out
        n //= 36
        if n == 0:
            return out


ranges, start = [], None
for code in range(0x110000):
    wide = unicodedata.east_asian_width(chr(code)) in ('W', 'F')
    if wide and start is None:
        start = code
    if not wide and start is not None:
        ranges.append((start, code - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))

previous, parts = 0, []
for first, last in ranges:
    parts.append(f'{b36(first - previous)}.{b36(last - first)}')
    previous = last

print(f'''/**
 * Display width of text in a search result snippet, same yardstick as personal-dashboard's
 * scripts/py/seo_rules.py `text_width()`: East Asian Wide / Fullwidth characters (CJK, fullwidth
 * punctuation) count 2, everything else 1. Google truncates snippets by pixels and a Chinese
 * glyph is about two Latin letters wide, so "160" means 160 Latin letters or 80 汉字.
 *
 * GENERATED by scripts/seo/gen-text-width.py from Python unicodedata {unicodedata.unidata_version} — do not edit by hand.
 */

// W/F ranges, delta-encoded in base 36: "<start - previous end>.<end - start>", comma-separated.
const WIDE_RANGES_ENCODED =
  '{','.join(parts)}';

const WIDE_RANGES: Array<[number, number]> = (() => {{
  const ranges: Array<[number, number]> = [];
  let previous = 0;
  for (const part of WIDE_RANGES_ENCODED.split(',')) {{
    const [gap, span] = part.split('.');
    const start = previous + parseInt(gap, 36);
    const end = start + parseInt(span, 36);
    ranges.push([start, end]);
    previous = end;
  }}
  return ranges;
}})();

export function isWideCodePoint(code: number): boolean {{
  let low = 0;
  let high = WIDE_RANGES.length - 1;
  while (low <= high) {{
    const middle = (low + high) >> 1;
    const [start, end] = WIDE_RANGES[middle];
    if (code < start) high = middle - 1;
    else if (code > end) low = middle + 1;
    else return true;
  }}
  return false;
}}

/** 汉字 / fullwidth = 2, everything else = 1, counted per code point (like Python's str). */
export function textWidth(text: string): number {{
  let width = 0;
  for (const char of text) width += isWideCodePoint(char.codePointAt(0)!) ? 2 : 1;
  return width;
}}''')
